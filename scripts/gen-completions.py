#!/usr/bin/env python3
"""Generate shell completions for cmux, cmux-tui, cmux-theme and cmux-gtk.

    gen-completions.py <path to cmux-tui> <output dir>

The command tree comes from the installed cmux-tui's own help (`cmux-tui
--help` and `cmux-tui <scope> --help`), so completions follow whatever
upstream revision is built. Writes:

    <out>/bash/cmux          (one file; also completes cmux-tui, cmux-theme, cmux-gtk)
    <out>/zsh/_cmux
    <out>/fish/cmux.fish, cmux-tui.fish, cmux-theme.fish, cmux-gtk.fish

Session names (running sockets and saved sessions) and theme names are
looked up when you press Tab, not baked in.
"""

import os
import re
import subprocess
import sys

GLOBAL_OPTIONS = ["--socket", "--session", "--machine", "--json", "--jsonl", "--quiet", "--help"]
THEME_ACTIONS = ["list", "set", "cycle", "install", "pair", "unpair"]


def help_text(binary, *args):
    try:
        out = subprocess.run([binary, *args, "--help"], capture_output=True, text=True, timeout=10)
        return out.stdout + out.stderr
    except (OSError, subprocess.TimeoutExpired):
        return ""


def words(token):
    """`a|b|c` -> [a, b, c]; drop placeholders and options."""
    return [w for w in token.split("|") if re.fullmatch(r"[a-z][a-z0-9-]*", w)]


def tree(binary):
    """{command: (direct actions, actions after a selector)}"""
    top = help_text(binary)
    commands = []
    for line in top.splitlines():
        # USAGE lines: `cmux-tui attach ...`, `cmux-tui server <a|b> ...`
        m = re.match(r"\s*cmux-tui ([a-z][a-z0-9-]*)\b", line)
        if m and m.group(1) not in commands:
            commands.append(m.group(1))
        # RESOURCE SCOPES: `  workspace     Create and organize workspaces`
        m = re.match(r"  ([a-z][a-z0-9-]*)\s{2,}\S", line)
        if m and m.group(1) not in commands:
            commands.append(m.group(1))
    # Agent shorthands listed in their own section.
    for extra in ["identify", "skill", "agent", "help"]:
        if extra not in commands:
            commands.append(extra)

    result = {}
    for command in commands:
        direct, after_selector = [], []
        for line in help_text(binary, command).splitlines() + top.splitlines():
            m = re.search(r"cmux-tui " + re.escape(command) + r" (\S+)(?: (\S+))?", line)
            if not m:
                continue
            first, second = m.group(1), m.group(2) or ""
            if first.startswith("<"):
                if first in ("<scope>",):
                    continue
                for w in words(second):
                    if w not in after_selector:
                        after_selector.append(w)
            elif first.startswith("["):
                continue
            else:
                for w in words(first):
                    if w not in direct:
                        direct.append(w)
        result[command] = (direct, after_selector)
    return result


def bash(t):
    cases = []
    for command, (direct, after) in sorted(t.items()):
        cases.append(f'        {command}) direct="{" ".join(direct)}"; after="{" ".join(after)}" ;;')
    return f"""# bash completion for cmux, cmux-tui, cmux-theme and cmux-gtk (generated by
# cmux-lin's scripts/gen-completions.py from cmux-tui's own help)

_cmux_sessions() {{
    local dir="${{XDG_RUNTIME_DIR:-/run/user/$(id -u)}}/cmux-tui-$(id -u)"
    local state="${{XDG_STATE_HOME:-$HOME/.local/state}}/cmux-tui/sessions"
    {{
        [ -d "$dir" ] && for f in "$dir"/*.sock; do [ -e "$f" ] && basename "$f" .sock; done
        [ -d "$state" ] && for d in "$state"/*-????????????????; do
            [ -d "$d" ] || continue; n=$(basename "$d"); n=${{n%-*}}
            [ "$n" = terminal-hosts ] || echo "$n"
        done
    }} | sort -u
}}

_cmux() {{
    local cur prev words cword
    _init_completion 2>/dev/null || {{ cur="${{COMP_WORDS[COMP_CWORD]}}"; prev="${{COMP_WORDS[COMP_CWORD-1]}}"; words=("${{COMP_WORDS[@]}}"); cword=$COMP_CWORD; }}
    case "$prev" in
        --session) COMPREPLY=($(compgen -W "$(_cmux_sessions)" -- "$cur")); return ;;
        --socket) COMPREPLY=($(compgen -f -- "$cur")); return ;;
    esac
    # Skip global options and their values to find the command.
    local i=1 command="" rest=()
    while [ $i -lt $cword ]; do
        case "${{words[i]}}" in
            --session|--socket|--machine) i=$((i+2)); continue ;;
            -*) i=$((i+1)); continue ;;
        esac
        if [ -z "$command" ]; then command="${{words[i]}}"; else rest+=("${{words[i]}}"); fi
        i=$((i+1))
    done
    if [ -z "$command" ]; then
        COMPREPLY=($(compgen -W "{" ".join(sorted(t))} {" ".join(GLOBAL_OPTIONS)}" -- "$cur"))
        return
    fi
    local direct="" after=""
    case "$command" in
{chr(10).join(cases)}
    esac
    if [ ${{#rest[@]}} -eq 0 ]; then
        COMPREPLY=($(compgen -W "$direct" -- "$cur"))
    elif [ ${{#rest[@]}} -eq 1 ] && ! [[ " $direct " == *" ${{rest[0]}} "* ]]; then
        COMPREPLY=($(compgen -W "$after" -- "$cur"))
    else
        COMPREPLY=($(compgen -W "--help {" ".join(GLOBAL_OPTIONS)}" -- "$cur"))
    fi
}}
complete -F _cmux cmux cmux-tui

_cmux_theme() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}"
    local themes="${{XDG_CONFIG_HOME:-$HOME/.config}}/cmux/themes"
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=($(compgen -W "{" ".join(THEME_ACTIONS)}" -- "$cur"))
    elif [ "$COMP_CWORD" -eq 2 ]; then
        case "${{COMP_WORDS[1]}}" in
            set|pair|unpair) COMPREPLY=($(compgen -W "$(ls "$themes" 2>/dev/null | sed -n 's/\\.json$//p')" -- "$cur")) ;;
            install) COMPREPLY=($(compgen -f -- "$cur")) ;;
        esac
    fi
}}
complete -F _cmux_theme cmux-theme

_cmux_gtk() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    if [ "$prev" = --session ]; then
        COMPREPLY=($(compgen -W "$(_cmux_sessions)" -- "$cur"))
    else
        COMPREPLY=($(compgen -W "--session" -- "$cur"))
    fi
}}
complete -F _cmux_gtk cmux-gtk
"""


def zsh(t):
    cases = []
    for command, (direct, after) in sorted(t.items()):
        cases.append(f"        ({command}) direct=({' '.join(direct)}); after=({' '.join(after)}) ;;")
    return f"""#compdef cmux cmux-tui cmux-theme cmux-gtk
# zsh completion (generated by cmux-lin's scripts/gen-completions.py from
# cmux-tui's own help)

_cmux_sessions() {{
    local dir="${{XDG_RUNTIME_DIR:-/run/user/$UID}}/cmux-tui-$UID"
    local state="${{XDG_STATE_HOME:-$HOME/.local/state}}/cmux-tui/sessions"
    local -a names
    names=(${{dir}}/*.sock(N:t:r))
    local d n
    for d in ${{state}}/*-????????????????(N/); do n=${{d:t}}; n=${{n%-*}}; [[ $n != terminal-hosts ]] && names+=($n); done
    compadd -a -- ${{(u)names}}
}}

_cmux_theme() {{
    local themes="${{XDG_CONFIG_HOME:-$HOME/.config}}/cmux/themes"
    if (( CURRENT == 2 )); then
        compadd -- {' '.join(THEME_ACTIONS)}
    elif (( CURRENT == 3 )); then
        case $words[2] in
            set|pair|unpair) compadd -- ${{themes}}/*.json(N:t:r) ;;
            install) _files ;;
        esac
    fi
}}

_cmux_main() {{
    if [[ $words[CURRENT-1] == --session ]]; then _cmux_sessions; return; fi
    if [[ $words[CURRENT-1] == --socket ]]; then _files; return; fi
    local -a rest; local command="" i=2
    while (( i < CURRENT )); do
        case $words[i] in
            --session|--socket|--machine) (( i += 2 )); continue ;;
            -*) (( i++ )); continue ;;
        esac
        if [[ -z $command ]]; then command=$words[i]; else rest+=($words[i]); fi
        (( i++ ))
    done
    if [[ -z $command ]]; then
        compadd -- {' '.join(sorted(t))} {' '.join(GLOBAL_OPTIONS)}
        return
    fi
    local -a direct after
    case $command in
{chr(10).join(cases)}
    esac
    if (( ${{#rest}} == 0 )); then
        compadd -a direct
    elif (( ${{#rest}} == 1 )) && (( ! ${{direct[(Ie)$rest[1]]}} )); then
        compadd -a after
    else
        compadd -- --help {' '.join(GLOBAL_OPTIONS)}
    fi
}}

case $service in
    cmux-theme) _cmux_theme ;;
    cmux-gtk) if [[ $words[CURRENT-1] == --session ]]; then _cmux_sessions; else compadd -- --session; fi ;;
    *) _cmux_main ;;
esac
"""


def fish(t, name):
    lines = [f"# fish completion for {name} (generated by cmux-lin's scripts/gen-completions.py)", ""]
    lines.append(
        "function __cmux_sessions\n"
        "    set -l uid (id -u)\n"
        "    set -l dir (set -q XDG_RUNTIME_DIR; and echo $XDG_RUNTIME_DIR; or echo /run/user/$uid)/cmux-tui-$uid\n"
        "    set -l state (set -q XDG_STATE_HOME; and echo $XDG_STATE_HOME; or echo $HOME/.local/state)/cmux-tui/sessions\n"
        "    for f in $dir/*.sock; basename $f .sock; end\n"
        "    for d in $state/*-????????????????; test -d $d; or continue\n"
        "        set -l n (basename $d | string replace -r -- '-[0-9a-f]{16}$' '')\n"
        "        test $n != terminal-hosts; and echo $n\n"
        "    end | sort -u\n"
        "end\n"
    )
    if name == "cmux-theme":
        lines.append(f"complete -c cmux-theme -f -n '__fish_use_subcommand' -a '{' '.join(THEME_ACTIONS)}'")
        lines.append(
            "complete -c cmux-theme -f -n '__fish_seen_subcommand_from set pair unpair' "
            "-a '(path change-extension \"\" (path basename (set -q XDG_CONFIG_HOME; and echo $XDG_CONFIG_HOME; or echo $HOME/.config)/cmux/themes/*.json))'"
        )
        return "\n".join(lines) + "\n"
    if name == "cmux-gtk":
        lines.append("complete -c cmux-gtk -f -l session -x -a '(__cmux_sessions)'")
        return "\n".join(lines) + "\n"
    lines.append(f"complete -c {name} -f")
    lines.append(f"complete -c {name} -l session -x -a '(__cmux_sessions)'")
    lines.append(f"complete -c {name} -l socket -r -F")
    for option in ["machine"]:
        lines.append(f"complete -c {name} -l {option} -x")
    for option in ["json", "jsonl", "quiet", "help"]:
        lines.append(f"complete -c {name} -l {option}")
    lines.append(f"complete -c {name} -n '__fish_use_subcommand' -a '{' '.join(sorted(t))}'")
    for command, (direct, after) in sorted(t.items()):
        if direct:
            lines.append(
                f"complete -c {name} -n '__fish_seen_subcommand_from {command}; and test (count (commandline -opc)) -le 2' "
                f"-a '{' '.join(direct)}'"
            )
        if after:
            lines.append(
                f"complete -c {name} -n '__fish_seen_subcommand_from {command}; and test (count (commandline -opc)) -eq 3' "
                f"-a '{' '.join(after)}'"
            )
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    binary, out = sys.argv[1], sys.argv[2]
    t = tree(binary)
    if not t or not any(direct for direct, _ in t.values()):
        sys.exit(f"couldn't read the command tree from {binary} --help")
    for sub in ("bash", "zsh", "fish"):
        os.makedirs(os.path.join(out, sub), exist_ok=True)
    with open(os.path.join(out, "bash", "cmux"), "w") as f:
        f.write(bash(t))
    with open(os.path.join(out, "zsh", "_cmux"), "w") as f:
        f.write(zsh(t))
    for name in ("cmux", "cmux-tui", "cmux-theme", "cmux-gtk"):
        with open(os.path.join(out, "fish", f"{name}.fish"), "w") as f:
            f.write(fish(t, name))
    print(f"completions for {len(t)} commands written to {out}")


if __name__ == "__main__":
    main()
